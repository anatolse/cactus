#include "backends/cpp-entt/cpp_entt_codegen.h"

#include "backends/cpp-entt/component_emitter.h"
#include "backends/cpp-entt/event_emitter.h"
#include "backends/cpp-entt/system_emitter.h"
#include "backends/cpp-manual/soa_emitter.h"

#include <sstream>

namespace cactus {

std::string CppEnttCodegen::generate(const DecoratedProgram& program) {
    std::ostringstream out;

    // Header
    out << "// Generated by Cactus DSL Compiler (cpp-entt backend)\n";
    out << "#pragma once\n\n";
    out << "#include <cstdint>\n";
    out << "#include <string>\n";
    out << "#include <vector>\n";
    out << "#include <entt/entt.hpp>\n";
    out << "#include \"raylib.h\"\n\n";

    // Enums
    for (auto& [name, e] : program.enums) {
        out << EnttComponentEmitter::emit_enum(e) << "\n";
    }

    // POD structs
    for (auto& [name, s] : program.structs) {
        out << EnttComponentEmitter::emit_pod_struct(s) << "\n";
    }

    // Component structs (from traits)
    for (auto& [name, t] : program.traits) {
        out << EnttComponentEmitter::emit_component(t) << "\n";
    }

    // Events
    if (program.ast) {
        for (auto& decl : program.ast->declarations) {
            if (auto* event = std::get_if<EventNode>(&decl)) {
                out << EnttEventEmitter::emit_event(*event, program) << "\n";
            }
        }
    }

    // Persist serialization stubs
    out << "// ── Persist Serialization ────────────────────────────────────────────\n\n";
    for (auto& [name, t] : program.traits) {
        bool has_persist = false;
        for (auto& f : t.fields) {
            if (f.is_persist) { has_persist = true; break; }
        }
        if (has_persist) {
            out << "void save_" << name << "(const " << name << "& comp) {\n";
            for (auto& f : t.fields) {
                if (f.is_persist) {
                    out << "    // serialize comp." << f.name << "\n";
                }
            }
            out << "}\n\n";
            out << "void load_" << name << "(" << name << "& comp) {\n";
            for (auto& f : t.fields) {
                if (f.is_persist) {
                    out << "    // deserialize into comp." << f.name << "\n";
                }
            }
            out << "}\n\n";
        }
    }

    // Sync replication stubs
    out << "// ── Sync Replication ─────────────────────────────────────────────────\n\n";
    for (auto& [name, t] : program.traits) {
        bool has_sync = false;
        for (auto& f : t.fields) {
            if (f.is_sync) { has_sync = true; break; }
        }
        if (has_sync) {
            out << "void replicate_" << name << "(const " << name << "& comp) {\n";
            for (auto& f : t.fields) {
                if (f.is_sync) {
                    out << "    // send delta for comp." << f.name << "\n";
                }
            }
            out << "}\n\n";
        }
    }

    // System functions
    if (program.ast) {
        out << "// ── Systems ─────────────────────────────────────────────────────────\n\n";
        for (auto& decl : program.ast->declarations) {
            if (auto* sys = std::get_if<SystemNode>(&decl)) {
                out << EnttSystemEmitter::emit_system(*sys, program);
            }
        }
    }

    // Entity creation from units
    if (program.ast) {
        out << "// ── Entity Creation ─────────────────────────────────────────────────\n\n";
        for (auto& decl : program.ast->declarations) {
            if (auto* unit = std::get_if<UnitNode>(&decl)) {
                out << "entt::entity create_" << unit->name << "(entt::registry& registry) {\n";
                out << "    auto entity = registry.create();\n";
                for (auto& trait_name : unit->apply.trait_names) {
                    out << "    registry.emplace<" << trait_name << ">(entity);\n";
                }
                out << "    return entity;\n";
                out << "}\n\n";
            }
        }
    }

    // Dispatcher setup
    if (program.ast) {
        out << "// ── Event Dispatcher ────────────────────────────────────────────────\n\n";
        out << "void setup_dispatcher(entt::dispatcher& dispatcher) {\n";
        for (auto& decl : program.ast->declarations) {
            if (auto* event = std::get_if<EventNode>(&decl)) {
                out << "    " << EnttEventEmitter::emit_sink_connection(*event);
            }
        }
        out << "}\n\n";
    }

    // Main game loop
    out << "// ── Main ────────────────────────────────────────────────────────────\n\n";
    out << "int main() {\n";
    out << "    InitWindow(800, 600, \"Cactus Game\");\n";
    out << "    SetTargetFPS(60);\n\n";
    out << "    entt::registry registry;\n";
    out << "    entt::dispatcher dispatcher;\n\n";

    out << "    while (!WindowShouldClose()) {\n";
    out << "        float dt = GetFrameTime();\n\n";

    // Call system tick handlers
    if (program.ast) {
        for (auto& decl : program.ast->declarations) {
            if (auto* sys = std::get_if<SystemNode>(&decl)) {
                for (auto& handler : sys->handlers) {
                    if (handler.event_name == "tick") {
                        out << "        " << sys->name << "_tick(registry, dt);\n";
                    }
                }
            }
        }
    }

    out << "        dispatcher.update();\n\n";
    out << "        BeginDrawing();\n";
    out << "        ClearBackground(RAYWHITE);\n";
    out << "        EndDrawing();\n";
    out << "    }\n\n";
    out << "    CloseWindow();\n";
    out << "    return 0;\n";
    out << "}\n";

    return out.str();
}

}  // namespace cactus
